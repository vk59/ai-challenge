#!/usr/bin/env python3
"""День 12: один и тот же вопрос через разные профили.

    python3 demo.py

Персонализацию нельзя проверить, глядя на один ответ: непонятно, это профиль
подействовал или модель просто так ответила. Поэтому здесь один вопрос
задаётся несколько раз — меняется только профиль, всё остальное неизменно:
модель, температура, история (её нет), роль.

Что меряется:
    форма      длина ответа, наличие кода, списков
    цена       профиль тоже занимает место в промпте
    послушание выполняется ли прямое ограничение из профиля
"""

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "shared"))

from agent import Agent, LLMError  # noqa: E402
from memory import Profile, SqliteStore  # noqa: E402
from tokens import money  # noqa: E402

TTY = sys.stdout.isatty()
DIM, BOLD, RED, GREEN, YELLOW, CYAN = "2", "1", "31", "32", "33", "36"


def paint(code: str, text: str) -> str:
    return f"\033[{code}m{text}\033[0m" if TTY else text


ВОПРОС = "Как мне хранить пароли пользователей в веб-приложении?"

ПРОФИЛИ = [
    Profile(
        "без профиля",
    ),
    Profile(
        "новичок",
        tone="дружелюбно и ободряюще",
        level="начинающий, первый год в программировании",
        format="пошагово, нумерованным списком, с коротким примером кода",
        language="русский",
    ),
    Profile(
        "senior",
        tone="сухо и по существу, как коллеге",
        level="senior-разработчик, 10 лет опыта",
        format="только суть, без введения и без объяснения базовых понятий",
        constraints="не объяснять, что такое хеш и зачем нужна соль",
    ),
    Profile(
        "аудитор",
        tone="формально",
        level="специалист по информационной безопасности",
        format="маркированный список требований со ссылками на стандарты",
        constraints="НЕ приводить примеры кода ни при каких условиях",
    ),
]

# Проверяем не «нравится ли ответ», а выполнено ли ПРЯМОЕ указание профиля.
# Это единственное, что можно проверить объективно.
ПОСЛУШАНИЕ = {
    "аудитор": ("без кода", lambda t: "```" not in t),
    "новичок": ("есть нумерация", lambda t: bool(re.search(r"^\s*1[.)]", t, re.M))),
    "senior": ("коротко, до 900 знаков", lambda t: len(t) < 900),
}


def прогнать(профиль: Profile, база: Path) -> dict | None:
    подпись = профиль.name
    print(paint(BOLD, f"\n  ── {подпись} ──"))
    предпочтения = профиль.filled
    if предпочтения:
        for подпись_поля, значение in предпочтения:
            print(paint(DIM, f"     {подпись_поля}: {значение[:62]}"))
    else:
        print(paint(DIM, "     (персонализации нет — контрольный замер)"))

    store = SqliteStore(база)
    agent = Agent(name="Ассистент", store=store, session=f"день12-{подпись}",
                  temperature=0.3, max_tokens=900)
    agent.reset()
    if предпочтения:
        agent.save_profile(профиль)

    вес = agent.weigh(ВОПРОС)
    try:
        ответ = agent.ask(ВОПРОС).strip()
    except LLMError as exc:
        print(paint(RED, f"     ошибка: {exc}"))
        return None

    проверка = ПОСЛУШАНИЕ.get(подпись)
    послушался = проверка[1](ответ) if проверка else None

    строк = len([s for s in ответ.splitlines() if s.strip()])
    print(paint(DIM, f"\n     {len(ответ)} знаков, {строк} строк, "
                     f"код: {'да' if '```' in ответ else 'нет'}"))
    if проверка:
        значок = paint(GREEN, "✓") if послушался else paint(RED, "✗")
        print(f"     {значок} указание «{проверка[0]}»")
    print(paint(DIM, "     ─── начало ответа ───"))
    for строка in ответ.splitlines()[:4]:
        print(paint(CYAN, f"     {строка[:72]}"))

    return {
        "имя": подпись,
        "знаков": len(ответ),
        "строк": строк,
        "код": "```" in ответ,
        "послушался": послушался,
        "профиль_токенов": вес["profile"],
        "вход": agent.stats.prompt_tokens,
        "выход": agent.stats.completion_tokens,
        "цена": agent.spent,
    }


def main() -> int:
    print(paint(BOLD, "\n  Один вопрос, разные профили\n"))
    print(f"  Вопрос: «{ВОПРОС}»")
    print(paint(DIM, "  Меняется ТОЛЬКО профиль: модель, температура и роль "
                     "одинаковые,\n  истории нет. Значит вся разница — от него."))

    база = Path(__file__).with_name("demo.db")
    база.unlink(missing_ok=True)

    итоги = [и for п in ПРОФИЛИ if (и := прогнать(п, база))]
    if len(итоги) < 2:
        return 1

    print(paint(BOLD, "\n\n  Итог\n"))
    print(f"  {'профиль':14} {'знаков':>7} {'строк':>6} {'код':>5} "
          f"{'указание':>9} {'профиль':>8} {'вход':>6} {'цена':>10}")
    print("  " + "─" * 76)
    for и in итоги:
        послушание = ("—" if и["послушался"] is None
                      else paint(GREEN, "выполн.") if и["послушался"]
                      else paint(RED, "НАРУШ. "))
        print(f"  {и['имя']:14} {и['знаков']:>7} {и['строк']:>6} "
              f"{'да' if и['код'] else 'нет':>5} {послушание:>9} "
              f"{и['профиль_токенов']:>8} {и['вход']:>6} {money(и['цена']):>10}")

    базовый = next((и for и in итоги if и["имя"] == "без профиля"), None)
    if базовый:
        print(paint(BOLD, "\n  Что из этого следует\n"))
        for и in итоги:
            if и["имя"] == "без профиля":
                continue
            разница = и["знаков"] - базовый["знаков"]
            знак = "+" if разница > 0 else ""
            print(f"    {и['имя']:10} {знак}{разница} знаков к контрольному, "
                  f"профиль весит {и['профиль_токенов']} токенов")
        print(paint(DIM, "\n    Профиль — это не бесплатно: он уезжает в каждый"))
        print(paint(DIM, "    запрос наравне с ролью. Зато форма ответа меняется"))
        print(paint(DIM, "    без единого слова в самом вопросе."))

    нарушения = [и["имя"] for и in итоги if и["послушался"] is False]
    if нарушения:
        print(paint(YELLOW, f"\n    Указание нарушено в профилях: "
                            f"{', '.join(нарушения)}."))
        print(paint(YELLOW, "    Профиль — просьба, а не гарантия: он часть промпта,"))
        print(paint(YELLOW, "    и модель может его проигнорировать."))

    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
