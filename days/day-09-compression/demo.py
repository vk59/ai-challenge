#!/usr/bin/env python3
"""День 9: сжатие истории — три режима на одном и том же диалоге.

    python3 demo.py            все три режима подряд
    python3 demo.py window     только узкое окно без сжатия
    python3 demo.py compress   только сжатие
    python3 demo.py full       только полная история

Задание требует сравнить качество ответов без сжатия и со сжатием, а заодно
расход токенов до и после. Чтобы сравнение было честным, все три режима
получают ОДИН И ТОТ ЖЕ диалог:

    1. в начале сообщаем агенту четыре факта, которые он не может угадать;
    2. потом уводим разговор в сторону на десяток реплик;
    3. в конце спрашиваем про факты из пункта 1.

Дальше просто считаем, сколько фактов агент вспомнил и во что это обошлось.
Угадать факты нельзя — они выдуманные, так что «вспомнил» означает именно
«информация доехала до модели», а не «модель догадалась».
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "shared"))

from agent import Agent, LLMError  # noqa: E402
from memory import SqliteStore  # noqa: E402
from tokens import money  # noqa: E402

TTY = sys.stdout.isatty()
DIM, BOLD, RED, GREEN, YELLOW, CYAN = "2", "1", "31", "32", "33", "36"


def paint(code: str, text: str) -> str:
    return f"\033[{code}m{text}\033[0m" if TTY else text


# ── диалог, одинаковый для всех режимов ─────────────────────────────────
# Факты нарочно выдуманные: угадать их модель не может, значит проверка
# честная. Ключ — то, что должно встретиться в ответе.
ФАКТЫ = [
    ("Запомни: кодовое слово нашего проекта — барракуда.", "барракуда"),
    ("Проект называется Гидра, и он про учёт складских остатков.", "гидра"),
    ("Я работаю в часовом поясе UTC+7, встречи раньше 11 не ставим.", "utc+7"),
    ("Наша база — PostgreSQL версии 14, мигрировать пока не планируем.", "postgres"),
]

# Болтовня, которая вытеснит факты из узкого окна
БОЛТОВНЯ = [
    "Назови одно короткое правило чистого кода.",
    "Чем список отличается от кортежа?",
    "Что такое идемпотентность?",
    "Назови один принцип SOLID.",
    "Зачем нужны индексы в базе данных?",
    "Что делает команда git rebase?",
    "Чем отличается процесс от потока?",
    "Что такое кэш-промах?",
    "Назови один способ ускорить запрос.",
    "Что такое техдолг?",
]

ПРОВЕРКА = [
    ("Какое кодовое слово у нашего проекта?", "барракуда"),
    ("Как называется проект и про что он?", "гидра"),
    ("В каком часовом поясе я работаю?", "utc+7"),
    ("Какая у нас база данных?", "postgres"),
]

РОЛЬ = ("Ты — ассистент-программист. Отвечай коротко, одним-двумя предложениями. "
        "Если чего-то не знаешь из разговора — так и скажи, не выдумывай.")

РЕЖИМЫ = {
    "full": ("полная история", dict(memory_turns=100, compress=False)),
    "window": ("узкое окно, без сжатия", dict(memory_turns=3, compress=False)),
    "compress": ("узкое окно + сжатие", dict(compress=True, keep_last=3,
                                             summarize_every=4)),
}


def прогнать(ключ: str, база: Path) -> dict | None:
    """Проводит один и тот же диалог в заданном режиме и считает результат."""
    подпись, настройки = РЕЖИМЫ[ключ]
    print(paint(BOLD, f"\n  ── {подпись} ──"))

    store = SqliteStore(база)
    # max_tokens=400, а не 90. Первая версия стояла на 90, и это ИСПОРТИЛО
    # сравнение: на длинном контексте модель не укладывалась в бюджет и
    # возвращала пустую строку с finish_reason=length. Счётчик записывал это
    # в «не вспомнил», и полная история выглядела забывчивой, хотя факты
    # помнила. Проверено отдельно: тот же вопрос на том же контексте с
    # max_tokens=400 отвечает верно.
    agent = Agent(name="Ассистент", role=РОЛЬ, store=store,
                  session=f"день9-{ключ}", temperature=0.3,
                  max_tokens=400, **настройки)
    agent.reset()      # каждый режим начинает с чистого листа

    # Прогресс печатаем с затиранием строки: без \r и добивки пробелами
    # строки склеиваются в одну мусорную простыню, которую потом стыдно
    # показывать на видео.
    def прогресс(текст: str) -> None:
        # Только в живом терминале: при перенаправлении в файл или конвейер
        # возврат каретки не затирает строку, и весь прогресс склеивается
        # в одну нечитаемую простыню.
        if not TTY:
            return
        print(paint(DIM, f"    {текст}".ljust(46)), end="\r", flush=True)

    try:
        # 1. Сообщаем факты
        for номер, (текст, _) in enumerate(ФАКТЫ, 1):
            agent.ask(текст)
            прогресс(f"факт {номер}/{len(ФАКТЫ)} сообщён")

        # 2. Уводим разговор в сторону
        for номер, вопрос in enumerate(БОЛТОВНЯ, 1):
            agent.ask(вопрос)
            прогресс(f"болтовня {номер}/{len(БОЛТОВНЯ)}")

        # 3. Спрашиваем про факты из начала
        print(" " * 46, end="\r")
        вспомнил = пусто = 0
        for вопрос, ключевое in ПРОВЕРКА:
            сырой = agent.ask(вопрос).strip()
            if not сырой:
                # Пустой ответ — это брак замера (обрыв по длине), а не
                # забывчивость агента. Считать его провалом памяти нельзя:
                # именно на этом первая версия демо и соврала.
                пусто += 1
                print(f"    {paint(YELLOW, '⚠')} {вопрос:38} → "
                      + paint(YELLOW, "ответ не пришёл, замер испорчен"))
                continue
            попал = ключевое in сырой.lower()
            вспомнил += попал
            значок = paint(GREEN, "✓") if попал else paint(RED, "✗")
            print(f"    {значок} {вопрос:38} → {сырой[:44]}")
    except LLMError as exc:
        print(paint(RED, f"    ошибка: {exc}"))
        return None

    s = agent.stats
    итог = {
        "ключ": ключ,
        "подпись": подпись,
        "вспомнил": вспомнил,
        "пусто": пусто,
        "диалог": s.dialogue_tokens,
        "сжатие": s.compression_tokens,
        "всего": s.total_tokens,
        "свёрток": s.compressions,
        "цена": agent.spent,
        "пересказ": agent.summary.content if agent.summary else "",
    }

    хвост = (f"    вспомнил {вспомнил} из {len(ПРОВЕРКА)} · "
             f"диалог {s.dialogue_tokens:,} токенов"
             + (f" + сжатие {s.compression_tokens:,}" if s.compressions else ""))
    print(paint(DIM, хвост))
    if пусто:
        print(paint(YELLOW, f"    внимание: {пусто} ответов не пришло — "
                            f"замер по этому режиму неполный"))
    return итог


def main() -> int:
    выбор = sys.argv[1] if len(sys.argv) > 1 else ""
    ключи = [выбор] if выбор in РЕЖИМЫ else list(РЕЖИМЫ)
    if выбор and выбор not in РЕЖИМЫ:
        print(__doc__)
        return 1

    print(paint(BOLD, "\n  Сжатие истории: три режима, один диалог"))
    print(f"  Сообщаем {len(ФАКТЫ)} факта → {len(БОЛТОВНЯ)} реплик болтовни → "
          f"{len(ПРОВЕРКА)} контрольных вопроса.")
    print(paint(DIM, "  Факты выдуманные: угадать их нельзя, значит проверка честная."))

    база = Path(__file__).with_name("demo.db")
    база.unlink(missing_ok=True)

    итоги = [и for к in ключи if (и := прогнать(к, база))]
    if len(итоги) < 2:
        return 0

    # ── сводка ──
    print(paint(BOLD, "\n\n  Итог\n"))
    print(f"  {'режим':24} {'вспомнил':>9} {'диалог':>9} {'сжатие':>8} "
          f"{'всего':>9} {'цена':>10}")
    print("  " + "─" * 74)
    for и in итоги:
        краска = GREEN if и["вспомнил"] == len(ПРОВЕРКА) else (
            RED if и["вспомнил"] == 0 else YELLOW)
        print(f"  {и['подпись']:24} "
              + paint(краска, f"{и['вспомнил']:>4} из {len(ПРОВЕРКА)}")
              + f" {и['диалог']:>9,} {и['сжатие']:>8,} "
                f"{и['всего']:>9,} {money(и['цена']):>10}")

    # Сравнение с полной историей — если она прогонялась
    полная = next((и for и in итоги if и["ключ"] == "full"), None)
    сжатие = next((и for и in итоги if и["ключ"] == "compress"), None)
    окно = next((и for и in итоги if и["ключ"] == "window"), None)

    print(paint(BOLD, "\n  Что из этого следует\n"))
    if окно and сжатие:
        print(f"    Узкое окно без сжатия вспомнило {окно['вспомнил']} фактов,")
        print(f"    то же окно со сжатием — {сжатие['вспомнил']}. Окно одинаковое,")
        print(f"    разница только в том, что вытесненное не выброшено, а свёрнуто.")
    if полная and сжатие:
        экономия = полная["всего"] - сжатие["всего"]
        доля = экономия / полная["всего"] * 100 if полная["всего"] else 0
        знак = "сэкономлено" if экономия > 0 else paint(RED, "ПЕРЕРАСХОД")
        print(f"\n    Против полной истории: {знак} {abs(экономия):,} токенов "
              f"({abs(доля):.0f}%),")
        print(f"    и это уже с учётом {сжатие['сжатие']:,} токенов, потраченных")
        print(f"    на сами свёртки ({сжатие['свёрток']} шт).")
        if экономия <= 0:
            print(paint(YELLOW, "\n    На таком коротком диалоге сжатие себя не окупает —"))
            print(paint(YELLOW, "    и это честный результат, а не поломка. Свёртка стоит"))
            print(paint(YELLOW, "    денег сразу, а экономит постепенно."))

        # Где проходит граница окупаемости. Считаем по уже собранным числам,
        # без единого нового запроса: у полной истории вес запроса растёт
        # с каждой репликой, у сжатия держится примерно на месте.
        реплик = len(ФАКТЫ) + len(БОЛТОВНЯ) + len(ПРОВЕРКА)
        полн_на_реплику = полная["всего"] / реплик
        сжат_на_реплику = сжатие["всего"] / реплик
        # Полная история дорожает линейно: средний вес ≈ половина последнего,
        # значит прирост на реплику ≈ 2 * средний / число реплик.
        прирост = 2 * полн_на_реплику / реплик
        print(paint(BOLD, "\n  Где сжатие начинает выигрывать\n"))
        print(f"    сейчас, на {реплик} репликах: полная {полная['всего']:,} "
              f"против {сжатие['всего']:,} у сжатия")
        if прирост > 0:
            # Ищем N, при котором площадь под растущей прямой обгонит
            # почти горизонтальную линию сжатия.
            рубеж = None
            for n in range(реплик, 400):
                полн = прирост * n * n / 2
                сжат = сжат_на_реплику * n
                if полн > сжат:
                    рубеж = n
                    break
            if рубеж:
                print(f"    примерно с {рубеж}-й реплики полная история становится")
                print(f"    дороже сжатия и дальше уходит в отрыв квадратично")
            else:
                print("    на обозримой длине диалога перелома не наступает")
        print(paint(DIM, "\n    Это прикидка по замеренным числам, а не теория:"))
        print(paint(DIM, "    вес запроса с полной историей растёт с каждой репликой,"))
        print(paint(DIM, "    а со сжатием держится почти на месте."))

    if сжатие and сжатие["пересказ"]:
        print(paint(BOLD, "\n  Во что свернулась история:\n"))
        for строка in сжатие["пересказ"].splitlines():
            if строка.strip():
                print(paint(CYAN, f"    {строка.strip()[:78]}"))

    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
