#!/usr/bin/env python3
"""День 10: три стратегии управления контекстом на одном сценарии.

    python3 demo.py              все три
    python3 demo.py window       только Sliding Window
    python3 demo.py facts        только Sticky Facts
    python3 demo.py branch       только Branching

Сценарий один и тот же — собираем ТЗ на складскую систему за 14 реплик,
по ходу дела меняя часть требований. Потом задаём контрольные вопросы.

Проверяются ровно те вещи, которые требует задание:

    качество      сколько фактов агент вспомнил
    стабильность  не потерял ли ИЗМЕНЁННЫЕ требования (самое трудное)
    расход        токены на диалог и токены на служебные запросы
    удобство      см. README, это не измеришь числом

Отдельно проверяется то, на чём стратегии обычно и ломаются: часть фактов
по ходу разговора МЕНЯЕТСЯ. Бюджет вырос, срок сдвинулся, база сменилась.
Правильный ответ — новое значение, а не старое и не оба сразу.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "shared"))

from agent import Agent, LLMError  # noqa: E402
from memory import SqliteStore  # noqa: E402
from tokens import money  # noqa: E402

TTY = sys.stdout.isatty()
DIM, BOLD, RED, GREEN, YELLOW, CYAN = "2", "1", "31", "32", "33", "36"


def paint(code: str, text: str) -> str:
    return f"\033[{code}m{text}\033[0m" if TTY else text


РОЛЬ = ("Ты — аналитик, помогаешь собрать техническое задание. "
        "Отвечай коротко, одним-двумя предложениями. "
        "Если чего-то не знаешь из разговора — скажи прямо, не выдумывай.")

# Сбор ТЗ. Часть требований по ходу МЕНЯЕТСЯ — это и есть проверка
# на стабильность: запомнить надо последнее значение, а не первое.
СЦЕНАРИЙ = [
    "Собираем ТЗ. Проект называется Гидра, это складской учёт остатков.",
    "Бюджет на первый этап — 800 тысяч рублей.",
    "Срок — три месяца, старт в марте.",
    "База данных PostgreSQL 14, менять не планируем.",
    "Интеграция с 1С обязательна, это ключевое требование.",
    "Назови один риск такого проекта.",
    "Что обычно забывают в ТЗ на складской учёт?",
    "Правки: бюджет подняли до полутора миллионов.",
    "Ещё правка: срок сдвинули на пять месяцев.",
    "И база — переезжаем на PostgreSQL 16, а не 14.",
    "Чем отличается инвентаризация от пересчёта?",
    "Назови один принцип хорошего API.",
    "Что такое партионный учёт?",
    "Какой формат обмена лучше для интеграции с 1С?",
]

# Что ДОЛЖНО быть в ответе. Три из шести проверяют, что агент запомнил
# именно ИЗМЕНЁННОЕ значение, а не первоначальное.
#
# Вариантов несколько на каждый вопрос, и это не придирка. Первая версия
# искала ровно одно слово — «полтора» и «пять» — и записала Sticky Facts
# в провал, хотя карточка фактов была верной: модель отвечает цифрами
# («1,5 миллиона», «5 месяцев»), а не прописью. Ещё хуже был ключ «да»:
# он подстрока слов «данных», «задача», и на ответе «из разговора это
# не следует» давал ложное попадание.
ПРОВЕРКА = [
    ("Как называется проект и про что он?", ["гидра"], False),
    ("Обязательна ли интеграция с 1С?", ["обязательн"], False),
    ("Какой сейчас бюджет проекта?", ["полтора", "1,5", "1.5", "1 500"], True),
    ("Какой сейчас срок?", ["пять", "5 мес", "5 мес."], True),
    ("Какая версия базы данных?", ["16"], True),
    ("Когда старт?", ["март"], False),
]

СТРАТЕГИИ = {
    "window": ("Sliding Window", dict(strategy="window", memory_turns=3)),
    "facts": ("Sticky Facts", dict(strategy="facts", memory_turns=3)),
    "branch": ("Branching", dict(strategy="branch", memory_turns=3)),
}


def прогресс(текст: str) -> None:
    if TTY:
        print(paint(DIM, f"    {текст}".ljust(52)), end="\r", flush=True)


# Обороты, которыми агент сообщает, что НЕ знает ответа. Если они есть —
# это промах, какие бы ключевые слова ни нашлись рядом.
#
# Без этой проверки матчер даёт ложные плюсы: на ответе «из разговора это
# не следует — про обязательность интеграции не говорилось» ключ
# «обязательн» честно находится внутри отрицания, и промах засчитывается
# как попадание. Подбирать ключи по одному бесполезно — ловить надо класс
# ошибки, а не отдельные случаи.
ОТРИЦАНИЯ = (
    "не назыв", "не обсужд", "не упомин", "не говорил", "не следует",
    "неизвестно", "не знаю", "нет данных", "не указан", "не сообщал",
    "не было", "не помню", "не могу",
)


def спросить(agent: Agent, вопрос: str, варианты: list[str]) -> tuple[bool, str, bool]:
    """Возвращает (попал, текст, пусто).

    Попал — если найден любой из вариантов И ответ не является отказом.
    """
    сырой = agent.ask(вопрос).strip()
    if not сырой:
        return False, "", True
    низ = сырой.lower()
    if any(о in низ for о in ОТРИЦАНИЯ):
        return False, сырой, False
    return any(в in низ for в in варианты), сырой, False


def прогнать(имя: str, база: Path) -> dict | None:
    подпись, настройки = СТРАТЕГИИ[имя]
    print(paint(BOLD, f"\n  ── {подпись} ──"))

    store = SqliteStore(база)
    agent = Agent(name="Аналитик", role=РОЛЬ, store=store,
                  session=f"день10-{имя}", temperature=0.3,
                  max_tokens=800, **настройки)
    agent.reset()

    try:
        for номер, реплика in enumerate(СЦЕНАРИЙ, 1):
            agent.ask(реплика)
            прогресс(f"реплика {номер}/{len(СЦЕНАРИЙ)}")

            # Branching: на середине сценария ставим checkpoint и расходимся
            # на две ветки. Дальше основная линия продолжается в ветке «А».
            if имя == "branch" and номер == 7:
                точка = agent.checkpoint()
                agent.fork(f"день10-branch-А", точка)
                agent.fork(f"день10-branch-Б", точка)
                прогресс(f"развилка на реплике {номер}: две ветки")

        print(" " * 52, end="\r")
        вспомнил = пусто = 0
        изменённых = 0
        for вопрос, варианты, менялось in ПРОВЕРКА:
            попал, текст, нет_ответа = спросить(agent, вопрос, варианты)
            if нет_ответа:
                пусто += 1
                print(f"    {paint(YELLOW, '⚠')} {вопрос:36} → "
                      + paint(YELLOW, "ответ не пришёл"))
                continue
            вспомнил += попал
            изменённых += попал and менялось
            значок = paint(GREEN, "✓") if попал else paint(RED, "✗")
            метка = paint(CYAN, " [изменённое]") if менялось else ""
            print(f"    {значок} {вопрос:36}{метка} → {текст[:38]}")
    except LLMError as exc:
        print(paint(RED, f"    ошибка: {exc}"))
        return None

    s = agent.stats
    print(paint(DIM, f"    вспомнил {вспомнил}/{len(ПРОВЕРКА)} "
                     f"(из них изменённых {изменённых}/3) · "
                     f"диалог {s.dialogue_tokens:,}"
                     + (f" + служебных {s.overhead_tokens:,}"
                        if s.overhead_tokens else "")))
    if пусто:
        print(paint(YELLOW, f"    внимание: {пусто} ответов не пришло"))

    return {
        "имя": имя, "подпись": подпись, "вспомнил": вспомнил,
        "изменённых": изменённых, "пусто": пусто,
        "диалог": s.dialogue_tokens, "служебные": s.overhead_tokens,
        "всего": s.total_tokens, "цена": agent.spent,
        "факты": list(agent.facts),
        "ветки": [b for b in agent.branches() if b.startswith("день10-branch-")],
    }


def main() -> int:
    выбор = sys.argv[1] if len(sys.argv) > 1 else ""
    если_одна = выбор in СТРАТЕГИИ
    if выбор and not если_одна:
        print(__doc__)
        return 1
    ключи = [выбор] if если_одна else list(СТРАТЕГИИ)

    print(paint(BOLD, "\n  Три стратегии управления контекстом, один сценарий"))
    print(f"  Собираем ТЗ за {len(СЦЕНАРИЙ)} реплик, по ходу МЕНЯЯ три требования.")
    print(f"  Потом {len(ПРОВЕРКА)} контрольных вопроса — три из них про изменённое.")
    print(paint(DIM, "  Окно у всех одинаковое: 3 пары. Разница только в стратегии."))

    база = Path(__file__).with_name("demo.db")
    база.unlink(missing_ok=True)

    итоги = [и for к in ключи if (и := прогнать(к, база))]
    if not итоги:
        return 1

    print(paint(BOLD, "\n\n  Итог\n"))
    print(f"  {'стратегия':18} {'вспомнил':>9} {'изменённых':>11} {'диалог':>9} "
          f"{'служебн.':>9} {'всего':>9} {'цена':>10}")
    print("  " + "─" * 80)
    for и in итоги:
        краска = (GREEN if и["вспомнил"] == len(ПРОВЕРКА)
                  else RED if и["вспомнил"] <= 2 else YELLOW)
        print(f"  {и['подпись']:18} "
              + paint(краска, f"{и['вспомнил']:>4}/{len(ПРОВЕРКА)}")
              + f" {и['изменённых']:>10}/3 {и['диалог']:>9,} "
                f"{и['служебные']:>9,} {и['всего']:>9,} {money(и['цена']):>10}")

    окно = next((и for и in итоги if и["имя"] == "window"), None)
    факты = next((и for и in итоги if и["имя"] == "facts"), None)

    print(paint(BOLD, "\n  Что из этого следует\n"))
    if окно and факты:
        print(f"    Окно у обеих стратегий одинаковое — 3 пары. Sliding Window")
        print(f"    вспомнил {окно['вспомнил']} из {len(ПРОВЕРКА)}, Sticky Facts — "
              f"{факты['вспомнил']}.")
        лишку = факты["всего"] - окно["всего"]
        print(f"\n    Факты обошлись дороже на {лишку:,} токенов: карточка")
        print(f"    обновляется отдельным запросом после КАЖДОЙ реплики.")
        print(f"    Это плата за то, что окно осталось узким, а память — нет.")
        if факты["изменённых"] > окно["изменённых"]:
            print(paint(GREEN, f"\n    Главное: изменённые требования. Факты удержали "
                               f"{факты['изменённых']} из 3,"))
            print(paint(GREEN, f"    окно — {окно['изменённых']}. Карточка "
                               f"перезаписывается по ключу,"))
            print(paint(GREEN, "    поэтому новое значение вытесняет старое, а не "
                               "ложится рядом."))

    if факты and факты["факты"]:
        print(paint(BOLD, "\n  Карточка фактов на конец диалога:\n"))
        for f in факты["факты"]:
            print(paint(CYAN, f"    {f.key}: {f.value}"[:78]))

    ветка = next((и for и in итоги if и["имя"] == "branch"), None)
    if ветка:
        print(paint(BOLD, "\n  Про Branching: его этой таблицей мерить нельзя\n"))
        print("    В колонке «вспомнил» у него мало — и это ожидаемо. Branching")
        print("    не улучшает память: под ним то же самое узкое окно, что")
        print("    и у Sliding Window. Он решает другую задачу — дать развилку,")
        print("    чтобы попробовать два продолжения от одного места и сравнить.")
        print(paint(DIM, "\n    Сравнивать его с Facts по числу запомненных фактов —"))
        print(paint(DIM, "    всё равно что сравнивать зонт с ботинками по размеру."))
        if ветка["ветки"]:
            store = SqliteStore(база)
            print(paint(BOLD, "\n    Его собственный результат — ветки от одной точки:\n"))
            for b in sorted(ветка["ветки"]):
                print(paint(CYAN, f"      {b}: {len(store.load(b))} реплик"))
            print(paint(DIM, "\n      Обе отошли от одного места и дальше независимы:"))
            print(paint(DIM, "      дописывание в одну не видно в другой."))

    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
