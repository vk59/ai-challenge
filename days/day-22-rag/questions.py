def проверить_корпус() -> int:
    """Убедиться, что ожидаемое действительно лежит в указанных источниках.

    Без этой проверки набор вопросов — пожелания. С ней видно, что RAG
    в принципе способен найти ответ, и промах будет промахом поиска
    или модели, а не следствием кривого ожидания.
    """
    from corpus import собрать

    документы = {д.path: д.text for д in собрать()}
    плохо = 0
    for номер, в in enumerate(ВОПРОСЫ, 1):
        отсутствуют = []
        for варианты in в["expect"]:
            где = [и for и in в["sources"] if и in документы
                   and any(в_.lower() in документы[и].lower() for в_ in варианты)]
            if not где:
                отсутствуют.append(" / ".join(варианты))
        нет_файлов = [и for и in в["sources"] if и not in документы]
        ладно = not отсутствуют and not нет_файлов
        плохо += not ладно
        print(f"  {'✓' if ладно else '✗'} {номер:2}. {в['q'][:58]}")
        if нет_файлов:
            print(f"        нет в корпусе: {', '.join(нет_файлов)}")
        if отсутствуют:
            print(f"        не нашлось в источниках: {', '.join(отсутствуют)}")
    return плохо


def main() -> None:
    if "--check" in sys.argv:
        sys.path.insert(0, str(ЗДЕСЬ.parents[1] / "days" / "day-21-indexing"))
        плохо = проверить_корпус()
        print(f"\nвопросов: {len(ВОПРОСЫ)}, с изъяном: {плохо}")
        sys.exit(1 if плохо else 0)

    for номер, в in enumerate(ВОПРОСЫ, 1):
        print(f"\n{номер}. {в['q']}")
        ожидания = "; ".join(" / ".join(в_) for в_ in в["expect"])
        print(f"   ждём в ответе : {ожидания}")
        print(f"   источники     : {', '.join(sorted(в['sources']))}")
        print(f"   почему честно : {в['why']}")
    print(f"\nвсего вопросов: {len(ВОПРОСЫ)}")


if __name__ == "__main__":
    main()
