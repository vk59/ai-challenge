#!/usr/bin/env python3
"""День 22: прогон десяти вопросов в двух режимах и сравнение.

    python3 evaluate.py             # оба режима, все вопросы
    python3 evaluate.py -v          # плюс тексты ответов
    python3 evaluate.py 3 7         # только выбранные вопросы
    python3 evaluate.py --mode rag  # только один режим
    python3 evaluate.py --chunks 10 # сколько кусков класть в промпт

Исход каждого ответа раскладывается на три, а не на два:

    попал      в ответе есть всё ожидаемое
    признался  честно сказал, что не знает или что в документах этого нет
    соврал     ответил уверенно, но не то

Разделять последние два обязательно. Модель, которая признаётся, безопасна:
видно, что надо искать самому. Модель, которая выдумывает правдоподобное
число, опаснее — ей верят. Сводить оба случая в «не попал» значит прятать
главное, что показывает этот день.
"""

import re
import sys
from pathlib import Path

ЗДЕСЬ = Path(__file__).resolve().parent
sys.path.insert(0, str(ЗДЕСЬ.parents[1] / "shared"))
sys.path.insert(0, str(ЗДЕСЬ))
sys.path.insert(0, str(ЗДЕСЬ.parents[0] / "day-21-indexing"))

from index import Index  # noqa: E402
from questions import ВОПРОСЫ  # noqa: E402
from rag import КУСКОВ, LLMError, спросить  # noqa: E402

# Признание незнания. Список накопился эмпирически: модель формулирует
# отказ десятком способов, и каждый пропущенный вариант превратил бы
# честный отказ в «соврал».
НЕЗНАНИЕ = re.compile(
    r"не знаю|не нахожу|нет данных|не располагаю|не указан|не найден|"
    r"в документах (этого|ничего) нет|в выдержках (этого|ничего) нет|"
    r"нет (этой|такой) информации|не содержится|не упомина|"
    r"уточните|не могу (сказать|ответить|определить)", re.I)


def исход(текст: str, ждём: list[list[str]]) -> str:
    """Все ожидания обязательны, каждое — любым из допустимых написаний."""
    низ = (текст or "").lower()
    if all(any(в.lower() in низ for в in варианты) for варианты in ждём):
        return "попал"
    return "признался" if НЕЗНАНИЕ.search(низ) else "соврал"


def разобрать_аргументы() -> tuple[list[int], list[str], bool, int]:
    кусков = КУСКОВ
    if "--chunks" in sys.argv:
        где = sys.argv.index("--chunks")
        if где + 1 < len(sys.argv) and sys.argv[где + 1].isdigit():
            кусков = int(sys.argv[где + 1])
            sys.argv.pop(где + 1)
    номера = [int(а) for а in sys.argv[1:] if а.isdigit()]
    режимы = ["plain", "rag"]
    if "--mode" in sys.argv:
        где = sys.argv.index("--mode")
        if где + 1 < len(sys.argv) and sys.argv[где + 1] in режимы:
            режимы = [sys.argv[где + 1]]
    подробно = "-v" in sys.argv or "--verbose" in sys.argv
    return номера, режимы, подробно, кусков


def main() -> None:
    номера, режимы, подробно, кусков = разобрать_аргументы()
    выбранные = [(н, в) for н, в in enumerate(ВОПРОСЫ, 1)
                 if not номера or н in номера]

    индекс = Index()
    счёт = {р: {"попал": 0, "признался": 0, "соврал": 0,
                "источники_верны": 0, "выдуманные_ссылки": 0,
                "токенов": 0, "секунд": 0.0} for р in режимы}

    ЗНАКИ = {"попал": "✓", "признался": "?", "соврал": "✗"}

    for номер, в in выбранные:
        print(f"\n{'─' * 74}")
        print(f"{номер}. {в['q']}")
        print(f"   ждём: {'; '.join(' / '.join(в_) for в_ in в['expect'])}")

        for режим in режимы:
            try:
                о = спросить(в["q"], режим=режим, индекс=индекс,
                             кусков=кусков)
            except LLMError as сбой:
                print(f"   {режим:5} — сбой: {сбой}")
                continue

            к = исход(о.text, в["expect"])
            счёт[режим][к] += 1
            счёт[режим]["токенов"] += о.total_tokens
            счёт[режим]["секунд"] += о.seconds

            хвост = ""
            if режим == "rag":
                верны = bool(set(о.sources) & в["sources"])
                счёт[режим]["источники_верны"] += верны
                счёт[режим]["выдуманные_ссылки"] += len(о.invented)
                хвост = (f"  источники {'✓' if верны else '✗'}"
                         f" {', '.join(и.split('/')[-2] + '/' + и.split('/')[-1]
                                       for и in о.sources) or '—'}")
            print(f"   {ЗНАКИ[к]} {режим:5} {к:10} "
                  f"{о.total_tokens:5} ток.  {о.seconds:4.1f}с{хвост}")
            if подробно:
                print(f"       {' '.join((о.text or '').split())[:260]}")

    print(f"\n{'═' * 74}")
    print(f"кусков в промпте: {кусков}")
    всего = len(выбранные)
    print(f"{'режим':8} {'попал':>7} {'признался':>11} {'соврал':>8} "
          f"{'источники':>11} {'токенов':>9}")
    for режим in режимы:
        с = счёт[режим]
        источники = (f"{с['источники_верны']}/{всего}" if режим == "rag"
                     else "—")
        print(f"{режим:8} {с['попал']:>5}/{всего:<2} {с['признался']:>9}  "
              f"{с['соврал']:>7} {источники:>11} {с['токенов']:>9,}"
              .replace(",", " "))

    if len(режимы) == 2:
        б, р = счёт["plain"], счёт["rag"]
        print(f"\nRAG добавил правильных ответов: "
              f"+{р['попал'] - б['попал']} из {всего}")
        print(f"Выдумок стало: {б['соврал']} → {р['соврал']}")
        if р["выдуманные_ссылки"]:
            print(f"⚠ выдуманных номеров ссылок: {р['выдуманные_ссылки']}")
        else:
            print("Ссылок на несуществующие выдержки: нет")
        цена = (р["токенов"] / б["токенов"]) if б["токенов"] else 0
        print(f"Токенов RAG тратит в {цена:.1f} раза больше "
              f"({б['токенов']:,} → {р['токенов']:,})".replace(",", " "))


if __name__ == "__main__":
    main()
