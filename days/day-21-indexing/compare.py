def оценить(индекс: Index, стратегия: str, подробно: bool = False) -> dict:
    попаданий_1 = попаданий_3 = 0
    обратные: list[float] = []
    промахи: list[tuple[str, set[str], list[str]]] = []

    for вопрос, ожидаем in ВОПРОСЫ:
        найденное = индекс.search(вопрос, стратегия, k=ГЛУБИНА)
        источники = [кусок.source for кусок, _ in найденное]

        место = next((н for н, и in enumerate(источники, 1) if и in ожидаем), 0)
        попаданий_1 += место == 1
        попаданий_3 += 1 <= место <= 3
        обратные.append(1 / место if место else 0.0)
        if not место:
            промахи.append((вопрос, ожидаем, источники))

        if подробно:
            знак = "1" if место == 1 else (str(место) if место else "—")
            print(f"\n  [{знак}] {вопрос[:68]}…")
            print(f"      ждали: {', '.join(sorted(ожидаем))}")
            for позиция, (кусок, оценка) in enumerate(найденное[:3], 1):
                метка = "✓" if кусок.source in ожидаем else " "
                print(f"      {метка} {позиция}. {оценка:.3f}  {кусок.source}"
                      f"  «{кусок.section[:34]}»")

    всего = len(ВОПРОСЫ)
    return {
        "strategy": стратегия,
        "questions": всего,
        "hit1": попаданий_1,
        "hit3": попаданий_3,
        "mrr": sum(обратные) / всего if всего else 0.0,
        "misses": промахи,
    }


def main() -> None:
    подробно = "-v" in sys.argv or "--verbose" in sys.argv
    индекс = Index()

    итоги = {}
    for стратегия in СТРАТЕГИИ:
        print(f"\n{'─' * 72}\n{стратегия}")
        try:
            итоги[стратегия] = оценить(индекс, стратегия, подробно)
        except IndexError_ as сбой:
            print(f"  {сбой}")
            return
        и = итоги[стратегия]
        print(f"\n  hit@1 {и['hit1']}/{и['questions']}"
              f"   hit@3 {и['hit3']}/{и['questions']}"
              f"   MRR {и['mrr']:.3f}")

    print(f"\n{'═' * 72}")
    print(f"{'':12} {'hit@1':>8} {'hit@3':>8} {'MRR':>8}")
    for стратегия, и in итоги.items():
        print(f"{стратегия:12} {и['hit1']:>5}/{и['questions']:<2} "
              f"{и['hit3']:>5}/{и['questions']:<2} {и['mrr']:>8.3f}")

    if len(итоги) == 2:
        б, с = итоги["fixed"], итоги["structural"]
        разница = с["mrr"] - б["mrr"]
        кто = ("structural" if разница > 0.02 else
               "fixed" if разница < -0.02 else "ничья")
        print(f"\nРазница MRR: {разница:+.3f} → {кто}")

    for стратегия, и in итоги.items():
        if и["misses"]:
            print(f"\nПромахи {стратегия}:")
            for вопрос, ожидаем, нашлось in и["misses"]:
                print(f"  · {вопрос[:64]}…")
                print(f"    ждали {', '.join(sorted(ожидаем))}, "
                      f"нашлось {', '.join(нашлось[:3])}")

    print(f"\nНа вопросы ушло: {РАСХОД.деньги_строкой} "
          f"(из кэша {РАСХОД.из_кэша} векторов)")


if __name__ == "__main__":
    main()
