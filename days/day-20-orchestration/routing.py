#!/usr/bin/env python3
"""День 20: карта маршрутов — один источник правды для окна и CLI.

Серверы не дублируются: подключаем ровно те, что написаны в дни 17–19.
Каждый отвечает за свою область, и в этом вся соль оркестрации — агент
должен понять, к кому идти, а не перебирать 19 инструментов подряд.

Отдельная забота — пересекающиеся инструменты. `git__search_commits`
и `pipe__search` оба ищут по репозиторию, и модель легко берёт не тот.
Разводим их не намёком, а прямым правилом в карте.
"""

import sys
from pathlib import Path

ЗДЕСЬ = Path(__file__).resolve().parent
ДНИ = ЗДЕСЬ.parents[0]

# Откуда брать серверы. В репозитории они лежат в своих папках дней, а внутри
# собранного .app всё сложено плоско рядом — поэтому сначала смотрим рядом.
# Дублировать код серверов не хочется: build_app.sh их просто копирует.
ОТКУДА = {
    "git":   ("server_git.py",   ДНИ / "day-17-mcp-tool" / "server.py"),
    "sched": ("server_sched.py", ДНИ / "day-18-scheduler" / "server.py"),
    "pipe":  ("server_pipe.py",  ДНИ / "day-19-pipeline" / "server.py"),
}


def _путь(рядом: str, в_репозитории: Path) -> Path:
    свой = ЗДЕСЬ / рядом
    return свой if свой.exists() else в_репозитории


# Три сервера, три области ответственности.
СЕРВЕРЫ: dict[str, list[str]] = {
    имя: [sys.executable, str(_путь(рядом, путь))]
    for имя, (рядом, путь) in ОТКУДА.items()
}

ОБЛАСТИ = {
    "git":   "факты о репозитории: коммиты, дни, файлы, GitHub",
    "sched": "фоновые задачи по расписанию",
    "pipe":  "конвейер: найти → сжать → сохранить в файл",
}

# Карта уезжает в системный промпт. Без неё модель на 19 инструментах
# начинает угадывать: берёт pipe__search там, где спрашивают про коммиты,
# и тянет весь конвейер ради одного факта.
КАРТА = """У тебя инструменты с ТРЁХ разных MCP-серверов. Сначала определи,
к какой области относится вопрос, и только потом выбирай инструмент.

git__*   — факты о репозитории. Сколько коммитов, что делалось в конкретный
           день, история файла, сведения о GitHub. Возвращают готовый ответ.
sched__* — фоновые задачи: завести, перечислить, выполнить сейчас, свести
           результаты. Всё, что про «регулярно», «по расписанию», «раз в».
pipe__*  — конвейер из трёх шагов: pipe__search кладёт найденное в артефакт,
           pipe__summarize сжимает артефакт по НОМЕРУ, pipe__save_to_file
           пишет артефакт по НОМЕРУ в файл.

Правила выбора, которые легко нарушить:

1. Спрашивают факт о репозитории — бери git__*. Конвейер для этого не нужен:
   pipe__search существует, чтобы готовить данные для сжатия и записи,
   а не чтобы отвечать на вопросы.
2. Нужен ФАЙЛ или выжимка — только тогда pipe__*, и обязательно всеми тремя
   шагами по порядку, передавая номер артефакта из ответа в ответ.
3. Просят делать что-то регулярно — sched__add_task. Не выполняй задачу
   руками вместо того, чтобы её завести.
4. В длинной просьбе несколько частей — выполни их все, по очереди,
   не останавливайся после первой.

Отвечай кратко и по делу, без пересказа того, что и так видно в вызовах."""

РОЛЬ = ("Ты — диспетчер инструментов. Обращайся к пользователю по имени, "
        "если знаешь его.\n\n" + КАРТА)

__all__ = ["СЕРВЕРЫ", "ОБЛАСТИ", "КАРТА", "РОЛЬ"]
