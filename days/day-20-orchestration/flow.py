from tools import MCPToolset  # noqa: E402

СЦЕНАРИИ = [
    {
        "имя": "факт о репозитории — только git",
        "запрос": "В какой день проекта было больше всего коммитов?",
        "servers": {"git"},
        "expect": ["git__commits_by_day"],
        # Главная ловушка дня: за фактом не надо ходить в конвейер.
        "forbid": ["pipe__search", "pipe__summarize", "pipe__run_pipeline"],
    },
    {
        "имя": "фоновые задачи — только sched",
        "запрос": "Какие фоновые задачи сейчас запланированы?",
        "servers": {"sched"},
        "expect": ["sched__list_tasks"],
        "forbid": ["git__repo_stats", "pipe__search"],
    },
    {
        "имя": "похожие инструменты на разных серверах",
        "запрос": "Найди коммиты, в сообщении которых упоминается MCP.",
        "servers": {"git"},
        "expect": ["git__search_commits"],
        "forbid": ["pipe__search"],
    },
    {
        "имя": "нужен файл — значит конвейер, все три шага по порядку",
        "запрос": ("Собери выжимку про планировщик из репозитория "
                   "и сохрани её в файл планировщик-20.md"),
        "servers": {"pipe"},
        "expect": ["pipe__search", "pipe__summarize", "pipe__save_to_file"],
        "order": ["pipe__search", "pipe__summarize", "pipe__save_to_file"],
    },
    {
        "имя": "длинный флоу через три сервера",
        "запрос": ("Сделай три вещи по порядку. Первое: узнай, сколько всего "
                   "коммитов в репозитории. Второе: найди в репозитории всё "
                   "про MCP, сожми это и сохрани в файл оркестрация.md. "
                   "Третье: заведи фоновую задачу со сводкой по репозиторию "
                   "раз в сутки."),
        "servers": {"git", "pipe", "sched"},
        "expect": ["pipe__search", "pipe__summarize", "pipe__save_to_file",
                   "sched__add_task"],
        "order": ["pipe__search", "pipe__summarize", "pipe__save_to_file"],
    },
]


def сервер_из(имя: str) -> str:
    return имя.split("__", 1)[0]


def проверить(сценарий: dict, вызовы: list[str]) -> list[tuple[bool, str]]:
    """Сверяет журнал вызовов с ожиданием. Возвращает список проверок."""
    итоги: list[tuple[bool, str]] = []
    задействованы = {сервер_из(в) for в in вызовы}

    нужны = сценарий.get("servers") or set()
    не_хватило = нужны - задействованы
    итоги.append((not не_хватило,
                  "серверы: " + (", ".join(sorted(задействованы)) or "ни одного")
                  + (f" — не хватило {', '.join(sorted(не_хватило))}"
                     if не_хватило else "")))

    пропущены = [и for и in сценарий.get("expect", []) if и not in вызовы]
    итоги.append((not пропущены,
                  "обязательные вызовы" + (f" — нет {', '.join(пропущены)}"
                                           if пропущены else " на месте")))

    лишние = [и for и in сценарий.get("forbid", []) if и in вызовы]
    итоги.append((not лишние,
                  "запрещённые вызовы" + (f" — есть {', '.join(лишние)}"
                                          if лишние else ": нет")))

    порядок = сценарий.get("order")
    if порядок:
        # Берём первое вхождение каждого: повторный вызов не должен
        # рушить проверку последовательности.
        места = [вызовы.index(и) if и in вызовы else -1 for и in порядок]
        ладно = all(м != -1 for м in места) and места == sorted(места)
        итоги.append((ладно, "порядок: " + " → ".join(
            и.split("__", 1)[1] for и in порядок)
            + ("" if ладно else " — нарушен")))
    return итоги


def прогнать(набор: MCPToolset, сценарий: dict, номер: int) -> bool:
    print(f"\n{'─' * 72}")
    print(f"{номер}. {сценарий['имя']}")
    print(f"   › {сценарий['запрос'][:150]}")

    агент = Agent(name="Диспетчер", role=РОЛЬ, temperature=0.2,
                  max_tokens=1200, memory_turns=0)
    агент.tools = набор
    агент.max_tool_rounds = 10

    было = len(набор.log)
    try:
        ответ = агент.ask(сценарий["запрос"])
    except LLMError as exc:
        print(f"   ✗ модель не ответила: {exc}")
        return False

    свежие = набор.log[было:]
    вызовы = [з.name for з in свежие]

    print()
    for шаг, запись in enumerate(свежие, 1):
        метка = "✗" if запись.failed else "·"
        print(f"   {метка} {шаг}. [{сервер_из(запись.name):5}] "
              f"{запись.name.split('__', 1)[1]}"
              f"({', '.join(f'{к}={v!r}'[:34] for к, v in запись.arguments.items())})"
              f"  {запись.seconds}с")
    if not свежие:
        print("   (инструменты не вызывались)")

    print()
    всё_ладно = True
    for ладно, текст in проверить(сценарий, вызовы):
        print(f"   {'✓' if ладно else '✗'} {текст}")
        всё_ладно = всё_ладно and ладно

    краткий = " ".join((ответ or "").split())
    print(f"\n   ответ: {краткий[:200]}{'…' if len(краткий) > 200 else ''}")
    return всё_ладно


def main() -> None:
    аргументы = sys.argv[1:]
    if "--list" in аргументы:
        for номер, с in enumerate(СЦЕНАРИИ, 1):
            print(f"{номер}. {с['имя']}")
        return

    выбранные = list(enumerate(СЦЕНАРИИ, 1))
    числа = [int(а) for а in аргументы if а.isdigit()]
    if числа:
        выбранные = [(н, с) for н, с in выбранные if н in числа]

    набор = MCPToolset(СЕРВЕРЫ)
    набор.open()
    print(f"Серверов: {len(СЕРВЕРЫ)} · {набор.describe()}")
    удачно = 0
    try:
        for номер, сценарий in выбранные:
            if прогнать(набор, сценарий, номер):
                удачно += 1
    finally:
        набор.close()

    print(f"\n{'═' * 72}")
    print(f"Сценариев пройдено: {удачно} из {len(выбранные)}")
    sys.exit(0 if удачно == len(выбранные) else 1)


if __name__ == "__main__":
    main()
