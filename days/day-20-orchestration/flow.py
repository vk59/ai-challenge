#!/usr/bin/env python3
"""День 20: проверка маршрутизации и порядка вызовов.

    python3 flow.py              # все сценарии
    python3 flow.py 5            # только пятый
    python3 flow.py --list       # перечислить, ничего не запуская

Задание требует проверить две вещи: правильно ли выбран инструмент и в
правильном ли порядке пошли вызовы. Поэтому у каждого сценария есть
ожидание, и оно проверяется машинно, а не на глаз:

    servers  — какие серверы обязаны участвовать
    expect   — инструменты, которые обязаны быть вызваны
    order    — те, чей ОТНОСИТЕЛЬНЫЙ порядок важен
    forbid   — инструменты, которых быть не должно (взял не тот сервер)

Порядок проверяется как относительный, а не как точное совпадение списка:
модель вправе добавить лишний уточняющий вызов, и это не ошибка. Ошибка —
сжать раньше, чем нашёл.
"""

