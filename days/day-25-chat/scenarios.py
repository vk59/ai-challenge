#!/usr/bin/env python3
"""День 25: два длинных сценария для проверки чата.

    python3 scenarios.py        # перечислить реплики и проверки

Задание требует проверить на двух сценариях по 10–15 сообщений, что
ассистент не теряет цель и продолжает выдавать источники. Поэтому
сценарии устроены не как список вопросов, а как разговор с ловушками:

    уточнения без подлежащего   «Сколько именно?», «А почему?» — ищется
                                в индексе нечего, если не раскрыть
    отвлечение в середине       вопрос в сторону, потом возврат к теме.
                                Цель обязана выжить
    фиксация ограничения        человек сообщает условие, и дальше оно
                                должно учитываться
    вопрос не по теме           ассистент обязан отказаться, но цель
                                при этом не потерять

У каждого сценария есть `goal_words`: слова, хотя бы одно из которых
обязано остаться в цели диалога до самого конца. Это и есть машинная
проверка «не теряет цель».
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import paths  # noqa: E402

paths.setup()

# kind: normal — обычная реплика, ждём источники
#       followup — уточнение без подлежащего, ждём раскрытие запроса
#       aside — отвлечение, цель меняться не должна
#       offtopic — вне базы, ждём отказ
#       constraint — человек фиксирует условие
#       meta — вопрос о самой переписке. Источники тут не требуются:
#              ответ лежит в истории и памяти задачи, а не в документах.
#              Требовать цитату на «с чего я начинал» было бы абсурдом
SCENARIOS: list[dict] = [
    {
        "name": "Разбор расходов на токены",
        "goal_words": ["токен", "сжат", "расход", "стоимост", "цен"],
        "messages": [
            ("Я разбираюсь, куда у проекта уходят токены. "
             "С чего начать смотреть?", "normal"),
            ("Как считается цена одного запроса?", "normal"),
            ("А сжатие истории это удорожает или наоборот?", "normal"),
            ("Сколько именно?", "followup"),
            ("А как вы это измеряли?", "followup"),
            ("У меня бюджет пятьдесят долларов в месяц, "
             "это вообще много для такого проекта?", "constraint"),
            ("Кстати, а какая погода сейчас в Лиссабоне?", "offtopic"),
            ("Ладно, вернёмся. Что из перечисленного дороже всего?",
             "followup"),
            ("А эмбеддинги в эту сумму входят?", "normal"),
            ("Сколько стоила полная сборка индекса?", "normal"),
            ("Что посоветуешь урезать первым?", "followup"),
            ("И напомни, с чего я начинал этот разговор?", "meta"),
        ],
    },
    {
        "name": "Как собрать поиск по своим документам",
        "goal_words": ["поиск", "индекс", "нарезк", "chunk", "документ", "rag"],
        "messages": [
            ("Хочу сделать поиск по своей документации. "
             "Что у вас для этого уже есть?", "normal"),
            ("Как документы режутся на куски?", "normal"),
            ("Какая стратегия лучше и почему?", "followup"),
            ("У меня документы — это в основном код на Python, "
             "без заголовков. Это меняет дело?", "constraint"),
            ("А по каким цифрам вы сравнивали стратегии?", "followup"),
            ("Что такое MRR?", "followup"),
            ("Погоди, а сколько человек это писало?", "offtopic"),
            ("Понятно. Так что мне ставить порогом отсечения?", "followup"),
            ("А реранкинг обязателен или можно без него?", "normal"),
            ("Во сколько он обходится?", "followup"),
            ("Что будет, если нужного куска в выдаче нет вообще?", "normal"),
            ("Сформулируй мне план действий по моей задаче.", "followup"),
            ("И какие были мои ограничения, помнишь?", "meta"),
        ],
    },
]


def main() -> None:
    for number, scenario in enumerate(SCENARIOS, 1):
        print(f"\n{number}. {scenario['name']} "
              f"({len(scenario['messages'])} реплик)")
        print(f"   цель держим по словам: {', '.join(scenario['goal_words'])}")
        for position, (message, kind) in enumerate(scenario["messages"], 1):
            print(f"   {position:2}. [{kind:10}] {message}")
    total = sum(len(s["messages"]) for s in SCENARIOS)
    print(f"\nвсего сценариев {len(SCENARIOS)}, реплик {total}")


if __name__ == "__main__":
    main()
